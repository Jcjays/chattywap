-- Asynchronous event processing, owned by the messaging feature: the transactional outbox, which the relay
-- publishes to RabbitMQ, and the deduplication record and effect of the example consumer.
--
-- Times written by the application (created_at, processed_at, updated_at) come from its clock, like every other
-- timestamp in the schema. The relay's own times (published_at, next_attempt_at after a claim or a failure) come
-- from PostgreSQL's clock (now()), so that several application instances claiming rows agree on when a claim
-- expires, whatever their clocks say.

-- Events waiting to be published, written in the same transaction as the change that produced them: either both
-- commit or neither does. The relay claims rows whose next_attempt_at has passed, publishes them, and sets
-- published_at once the broker has confirmed them. A failed attempt keeps the row pending, with a later
-- next_attempt_at. Rows are never deleted: published ones stay for investigation (there is no cleanup yet).
create table outbox_events (
    -- The event ID: also the payload's eventId and the AMQP message ID. Generated by the application.
    id              uuid          primary key,
    event_type      varchar(100)  not null,
    event_version   integer       not null,
    routing_key     varchar(255)  not null,
    -- The event as JSON, exactly the message body that is published.
    payload         text          not null,
    created_at      timestamptz   not null,
    -- When the broker confirmed the event. Null while it is pending.
    published_at    timestamptz,
    -- Publication attempts so far, counted when the relay claims the row.
    attempts        integer       not null default 0,
    -- When the relay may claim the row: its creation time at first, then the end of a claim's lease, or of the
    -- delay after a failed attempt.
    next_attempt_at timestamptz   not null,
    -- Why the latest failed attempt failed. Kept after a later attempt succeeds.
    last_error      varchar(1000),
    constraint outbox_events_payload_is_json check (payload is json object),
    constraint outbox_events_event_version_positive check (event_version > 0),
    constraint outbox_events_attempts_not_negative check (attempts >= 0)
);

-- The relay's claim: "where published_at is null and next_attempt_at <= now() order by next_attempt_at limit n".
-- Partial, so it holds only pending rows: published rows, the vast majority over time, neither grow it nor slow the
-- claim down. Also serves the pending count and the oldest pending event's age (metrics).
create index outbox_events_pending_idx on outbox_events (next_attempt_at) where published_at is null;

-- Events a consumer has processed. RabbitMQ delivers at least once, so a consumer can receive an event again (the
-- relay published it twice, or the broker redelivered it). Each consumer records the event in the same transaction
-- as its effect; a second delivery finds the row and changes nothing.
create table processed_events (
    consumer_name varchar(100) not null,
    event_id      uuid         not null,
    processed_at  timestamptz  not null,
    primary key (consumer_name, event_id)
);

-- The example consumer's effect: how many MessageCreated events it has processed per conversation. Not read by the
-- API. A duplicate that was applied twice would show as a count that is too high, which is what the idempotency
-- tests check.
create table conversation_message_counts (
    conversation_id uuid        primary key references conversations (id) on delete restrict,
    message_count   bigint      not null,
    updated_at      timestamptz not null,
    constraint conversation_message_counts_positive check (message_count > 0)
);
